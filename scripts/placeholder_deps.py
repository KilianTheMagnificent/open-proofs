#!/usr/bin/env python3
"""Find upstream theorems that are written with a proof but still depend on a placeholder.

For every upstream theorem whose body is not the placeholder, print its axioms and report those
that include `sorryAx`. Such a theorem looks proved but rests on an unproved lemma (often an
API lemma); proving that lemma here discharges it. Some are intentional (conditional results
that cite an open statement), so each lead needs a look. Not part of the trusted checker.

Usage:
  python3 scripts/placeholder_deps.py --subdir ErdosProblems [--workers 6] [--resume]
  python3 scripts/placeholder_deps.py --report      # write ledger/placeholder-deps.md from results
Writes work/placeholder_deps/results.jsonl and prints the leads.
Requires the upstream modules to be built.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import quickkill  # noqa: E402
import triage  # noqa: E402

ROOT = quickkill.ROOT
UP = quickkill.UP
OUT = ROOT / "work" / "placeholder_deps"


def run_file(path: Path, decls: list[dict], timeout: int) -> list[dict]:
    module = triage.module_name(path)
    lines = [f"import {module}", ""] + [f"#print axioms {quickkill.lean_name(d['decl'])}" for d in decls]
    OUT.mkdir(parents=True, exist_ok=True)
    rel = path.relative_to(UP / "FormalConjectures")
    gen = OUT / ("_".join(rel.with_suffix("").parts) + ".lean")
    gen.write_text("\n".join(lines) + "\n")
    try:
        p = subprocess.run(["lake", "env", "lean", str(gen)], cwd=ROOT, env=quickkill.env(),
                           capture_output=True, text=True, timeout=timeout)
        out = p.stdout + p.stderr
    except subprocess.TimeoutExpired:
        out = ""
    axioms: dict[str, list[str]] = {}
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", out):
        axioms[m.group(1)] = [x.strip() for x in m.group(2).split(",") if x.strip()]
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", out):
        axioms[m.group(1)] = []
    res = []
    for d in decls:
        key = d["decl"].replace("«", "").replace("»", "")
        ax = axioms.get(key)
        if ax is None:
            ax = next((v for k, v in axioms.items() if k.replace("«", "").replace("»", "") == key), None)
        res.append({"file": str(path.relative_to(UP)), "decl": d["decl"], "category": d["category"],
                    "axioms": ax, "rests_on_placeholder": bool(ax) and "sorryAx" in ax})
    return res


def report() -> int:
    rows = [json.loads(l) for l in (OUT / "results.jsonl").read_text().splitlines() if l.strip()]
    leads = [r for r in rows if r["rests_on_placeholder"]]
    up = json.loads((ROOT / "upstream.json").read_text())["formal_conjectures"]["commit"]
    md = ["# Upstream theorems written with a proof that still rest on a placeholder", "",
          f"Generated by `scripts/placeholder_deps.py --report` (formal-conjectures `{up[:12]}`).",
          f"{len(rows)} written proofs scanned, {len(leads)} depend on `sorryAx`. Some are intentional",
          "(conditional results citing an open or externally proved statement); others rest on an unproved",
          "API lemma that could be proved here. Each is a lead for the queue, not a finding.", "",
          "| declaration | category | file |", "|---|---|---|"]
    md += [f"| `{r['decl']}` | {r['category']} | `{r['file']}` |" for r in leads]
    (ROOT / "ledger" / "placeholder-deps.md").write_text("\n".join(md) + "\n")
    print(f"{len(leads)} lead(s) written to ledger/placeholder-deps.md")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--subdir", default="ErdosProblems")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()
    if args.report:
        return report()
    base = UP / "FormalConjectures" / args.subdir
    OUT.mkdir(parents=True, exist_ok=True)
    resf = OUT / "results.jsonl"
    done = set()
    if args.resume and resf.exists():
        done = {json.loads(l)["file"] for l in resf.read_text().splitlines() if l.strip()}
    jobs = []
    for p in sorted(base.rglob("*.lean")):
        if str(p.relative_to(UP)) in done:
            continue
        decls = [d for d in triage.parse_file(p) if not d["sorry"]]
        if decls:
            jobs.append((p, decls))
    print(f"{len(jobs)} file(s), {sum(len(d) for _, d in jobs)} written proof(s)")
    n = 0
    with ThreadPoolExecutor(max_workers=args.workers) as ex, resf.open("a") as fh:
        for res in ex.map(lambda j: run_file(j[0], j[1], args.timeout), jobs):
            for r in res:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
                if r["rests_on_placeholder"]:
                    n += 1
                    print(f"LEAD {r['category']}  {r['decl']}  ({r['file']})", flush=True)
            fh.flush()
    print(f"{n} lead(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
