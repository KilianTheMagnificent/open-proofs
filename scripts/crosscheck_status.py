#!/usr/bin/env python3
"""Cross-check upstream Erdős problem categories against the erdosproblems.com database.

Compares the `@[category research open|solved]` tag of each main theorem `erdos_N` in the pinned
formal-conjectures checkout with `informal_status.state` in teorth/erdosproblems
`data/problems.yaml` (pinned in upstream.json; fetch with scripts/fetch_erdos_db.sh), and writes
`ledger/status-crosscheck.md`. A mismatch is a lead, not a verdict: either source may lag.

Usage: python3 scripts/crosscheck_status.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import triage  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
UP = ROOT / ".lake" / "packages" / "formal_conjectures" / "FormalConjectures" / "ErdosProblems"
OPEN = {"open", "falsifiable", "verifiable", "decidable", "not provable", "not disprovable"}
SOLVED = {"solved", "proved", "disproved", "independent"}


def main() -> int:
    up = json.loads((ROOT / "upstream.json").read_text())
    db = triage.load_erdos_status(ROOT / "work" / "erdos-db" / "problems.yaml")
    if not db:
        print("missing work/erdos-db/problems.yaml: run scripts/fetch_erdos_db.sh", file=sys.stderr)
        return 1
    rows, n_main = [], 0
    for p in sorted(UP.glob("*.lean"), key=lambda p: int(p.stem)):
        n = p.stem
        mains = [d for d in triage.parse_file(p) if d["decl"].endswith(f".erdos_{n}") or d["decl"] == f"erdos_{n}"]
        if not mains:
            continue
        n_main += 1
        d = mains[0]
        e = db.get(n, {})
        inf, formal = e.get("informal_status.state"), e.get("formal_status.state")
        cat = d["category"]
        kind = None
        if cat == "research open" and inf in SOLVED:
            kind = "upstream open, DB solved"
        elif cat == "research solved" and inf in OPEN:
            kind = "upstream solved, DB open"
        if kind:
            rows.append(f"| [{n}](https://www.erdosproblems.com/{n}) | {kind} | {cat} | {inf} | {formal} | "
                        f"{'yes' if d['formal_proof'] else 'no'} | {'yes' if d['sorry'] else 'no'} |")
    md = [
        "# Erdős status cross-check",
        "",
        f"Generated by `scripts/crosscheck_status.py`. formal-conjectures `{up['formal_conjectures']['commit'][:12]}` "
        f"vs teorth/erdosproblems `{up['erdosproblems_db']['commit'][:12]}` (`data/problems.yaml`).",
        f"{n_main} problems have a main theorem `erdos_N`; {len(rows)} disagree on open/solved.",
        "",
        "A disagreement is a lead, not a verdict: either source can lag. \"upstream solved, DB open\" rows",
        "usually cite an external `formal_proof` link that the DB has not yet absorbed; re-verifying such",
        "external proofs with this project's checker is a candidate activity (see docs/TODO.md).",
        "",
        "| problem | disagreement | upstream category | DB informal | DB formal | upstream formal_proof link | upstream body is placeholder |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    (ROOT / "ledger" / "status-crosscheck.md").write_text("\n".join(md))
    print(f"{len(rows)} disagreements written to ledger/status-crosscheck.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
